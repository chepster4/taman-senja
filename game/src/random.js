// A tiny deterministic random source. Every scene draws from a seed, so the left
// and right panels of one scene are pixel-identical except for their differences,
// and the same seed always paints the same garden.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function range(rng, min, max) {
  return min + rng() * (max - min);
}

export function pick(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function integer(rng, min, max) {
  return min + Math.floor(rng() * (max - min + 1));
}
